"""
KucLab Hertz 0.7 — dataset assembly (Gemma-4-12B base, same as 0.4/0.5/0.6).

LINEAGE: reuse is back to being the default, not the exception
----------------------------------------------------------------
0.6 taught us (the hard way, across three training attempts) that a single
round of "everything fresh" data loses the cumulative Czech/STEM
reinforcement that 0.3→0.4→0.5→0.6 had each built up by carrying forward
the prior release's corpus. So 0.7 reuses 0.6's FULL train.jsonl (2932
rows — which itself already contains 0.5's corpus, which contains 0.4's,
which contains 0.3's terminology work) and adds a large fresh STEM-heavy
batch on top, generated by a subagent this round (not an external chatbot
like 0.6, not self-distillation like 0.3-0.5).

GOAL: push MMLU-Pro STEM from 0.6's 79.2% toward 85%
-------------------------------------------------------
0.6 beat the base model (75.8%) and every prior release by training
specifically on ANSWER-FIRST FORMAT (state the conclusion before the
derivation) — this cut unparseable/wrong answers from 46/240 in 0.5 to
18/240 in 0.6, a direct, measured, non-artifact improvement. ANSWER_FORMAT_
ROWS below is expanded significantly from 0.6's 8 examples on the strength
of that result. The fresh subagent-generated batch is STEM-depth weighted
(harder multi-step problems, not just concept recall) to push the ceiling
further, not just the floor.

BENCHMARK HONESTY — the line this file does not cross
------------------------------------------------------
cz_terms.py holds out every 4th term (index % 4 == 3) as an eval set.
build() uses train_terms() ONLY. No MMLU-Pro question ever enters training
data — the answer-first FORMAT is taught, the test's actual questions are
not. The fresh batch was generated by a subagent instructed never to write
model-identity questions and never to phrase rows as bare benchmark-style
lookups (the mistake that regressed Czech terminology in 0.6's first
attempt — see scripts/build_hertz06_dataset.py's terminology_rows()
docstring for the full story).

USAGE
  .venv/bin/python scripts/build_hertz07_dataset.py build --fresh <path.jsonl>
"""
